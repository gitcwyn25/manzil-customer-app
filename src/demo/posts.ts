/** Seed reference time. All demo timestamps are illustrative. */
const at = (daysAgo: number, hour: number, minute = 0) => {
  const d = new Date(Date.UTC(2026, 10, 13, hour - 5, minute));
  d.setUTCDate(d.getUTCDate() - daysAgo);
  return d.toISOString();
};

